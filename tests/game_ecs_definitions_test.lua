local ECS = require("src.engine.ecs")
local registerBreakout = require("src.game.ecs.register")

return function()
    local first, second = ECS.World.new(), ECS.World.new()
    registerBreakout(first)
    registerBreakout(second)
    first:setResource("match", { status = "playing", remainingBricks = 50 })
    second:setResource("match", { status = "lost", remainingBricks = 0 })
    first:setResource("input", { left = true, keys = { left = true } })
    second:setResource("input", {})
    local firstEntity = first:create({ position = { x = 1, y = 2 } })
    local secondEntity = second:create({ position = { x = 3, y = 4 } })
    first:get(firstEntity, "position").x = 99
    assert(second:get(secondEntity, "position").x == 3)
    assert(first:requireResource("match") ~= second:requireResource("match"))
    assert(first:componentDefinition("position") ~= second:componentDefinition("position"))
    assert(not pcall(function()
        first:setResource("match", { status = "invalid", remainingBricks = 0 })
    end))
    assert(not pcall(function() first:emit("keyPressed", { key = "" }) end))
    assert(not pcall(function() first:emit("sceneRequest", { to = "" }) end))
    first:emit("keyPressed", { key = "space" })
    first:advanceEvents()
    assert(first:eventCount("keyPressed") == 1)
    first:dispose(); second:dispose()
end
