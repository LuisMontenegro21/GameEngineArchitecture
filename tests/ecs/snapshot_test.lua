local World = require("src.engine.ecs.World")
local Snapshot = require("src.engine.ecs.Snapshot")
local Prefab = require("src.engine.ecs.Prefab")

return function()
    local world = World.new()
    world:registerComponent("position", { version = 2, migrate = function(v) return { x = v.x, y = v.y } end })
    world:registerComponent("tag", { tag = true })
    world:registerResource("score", { version = 1 })
    world:registerResource("service", { transient = true })
    local root = world:create({ position = { x = 2, y = 3 }, tag = true })
    local child = world:create({ position = { x = 4, y = 5 } }); world:setParent(child, root)
    world:setResource("score", 42); world:setResource("service", {})
    local saved = Snapshot.capture(world)
    assert(saved.resources.score and not saved.resources.service)

    local restored = World.new()
    restored:registerComponent("position", { version = 2, migrate = function(v) return v end })
    restored:registerComponent("tag", { tag = true })
    restored:registerResource("score", { version = 1 })
    local remap = Snapshot.restore(restored, saved)
    assert(restored:count() == 2 and restored:getResource("score") == 42)
    assert(restored:getParent(remap[child.id]).id == remap[root.id].id)

    local old = { version = 1, entities = {{ id = 9, components = { position = { version = 1, value = { x = 7, y = 8 } } } }}, resources = {} }
    local migrationWorld = World.new()
    migrationWorld:registerComponent("position", { version = 2, migrate = function(v) return { x = v.x, y = v.y } end })
    local migrated = Snapshot.restore(migrationWorld, old)
    assert(migrationWorld:get(migrated[9], "position").x == 7)
    local before = restored:count()
    assert(not pcall(function() Snapshot.restore(restored, { version = 1, entities = {{ id = 1, components = { missing = { version = 1, value = {} } } }}, resources = {} }) end))
    assert(restored:count() == before)

    local prefab = Prefab.capture(world, root)
    local a = Prefab.instantiate(restored, prefab)
    local b = Prefab.instantiate(restored, prefab, { position = { x = 99, y = 99 } })
    assert(a and b and a.id ~= b.id)
    restored:set(b, "position", { x = 100, y = 100 })
    assert(restored:get(a, "position").x ~= restored:get(b, "position").x)
end
